-- Rodzaje produktów (24.11.2026): porównywanie cen po rodzaju, a nie po identycznym produkcie.
-- Decyzje zespołu z 23.11.2026 i projekt: Dane_sklepy_current/rodzaje_produktow/PROJEKT_rodzaje_produktow.md
-- (po wdrożeniu: docs/rodzaje-produktow.md). Kontrakt API: docs/api-katalogu.md.
--
-- kategoria -> podkategoria -> [produkt bazowy] -> RODZAJ -> produkty -> oferty w sieciach
-- * Rodzaj należy do podkategorii. Produkt dostaje rodzaj z reguł (wzorce na znormalizowanej nazwie, w kolejności
--   priorytetu) albo z ręcznej decyzji (product_type_reviews, ma pierwszeństwo). Importer się nie zmienia: rodzaj
--   przypisuje wyzwalacz, tak jak klasyfikację mleka. Produkty bazowe zostają bez zmian.
-- * Produkt bez rodzaju zostaje pojedynczym produktem (stare grupy zamienników działają jak dotąd).
-- * Porównanie: w każdej sieci JEDEN produkt rodzaju, który najtaniej pokrywa ilość (bez mieszania marek);
--   wybór klienta w sieci działa też w innych sieciach, które mają ten sam produkt (product_id).
-- * Cena podejrzana: cena za kg / l / szt poniżej 40% albo powyżej 300% mediany rodzaju (przy co najmniej 5 ofertach).
--   Taka oferta jest widoczna (suspicious: true), ale nie wygrywa jako najtańsza.
-- Obecne funkcje i odpowiedzi działają bez zmian; nowe zachowanie włącza parametr p_with_types albo pozycja z type_id.

-- 1. Tabele ----------------------------------------------------------------------------------------------------------
CREATE TABLE public.product_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 100),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
  subcategory_id bigint NOT NULL REFERENCES public.catalog_subcategories(id) ON DELETE RESTRICT,
  unit text NOT NULL CHECK (unit IN ('g', 'ml', 'szt')),
  g_ml_equal boolean NOT NULL DEFAULT false,          -- płynny nabiał: 1 g = 1 ml (sieci podają raz g, raz ml)
  default_quantity numeric(12,2) CHECK (default_quantity > 0),   -- NULL = typowe opakowanie
  typical_package numeric(12,2) CHECK (typical_package > 0),     -- mediana gramatury produktów (refresh_product_types)
  display_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  search_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT g_ml_equal OR unit IN ('g', 'ml'))
);
CREATE INDEX product_types_subcategory ON public.product_types(subcategory_id, display_order);

CREATE TABLE public.product_type_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_type_id bigint NOT NULL REFERENCES public.product_types(id) ON DELETE CASCADE,
  priority integer NOT NULL UNIQUE,                    -- pierwsza pasująca reguła (najniższy priorytet) wygrywa
  base_product_names text[] NOT NULL CHECK (cardinality(base_product_names) BETWEEN 1 AND 50),
  include_pattern text NOT NULL CHECK (length(include_pattern) BETWEEN 1 AND 1000),   -- regex na catalog_search_norm(nazwa)
  exclude_pattern text CHECK (length(exclude_pattern) BETWEEN 1 AND 1000),
  note text
);

CREATE TABLE public.product_type_reviews (
  product_id bigint PRIMARY KEY REFERENCES public.products(id) ON DELETE CASCADE,
  product_type_id bigint REFERENCES public.product_types(id) ON DELETE CASCADE,   -- NULL = bez rodzaju
  source text NOT NULL CHECK (length(source) BETWEEN 1 AND 200),
  reviewed_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.products
  ADD COLUMN product_type_id bigint REFERENCES public.product_types(id) ON DELETE SET NULL,
  ADD COLUMN product_type_source text CHECK (product_type_source IN ('rule', 'review'));
CREATE INDEX products_product_type ON public.products(product_type_id) WHERE product_type_id IS NOT NULL;

CREATE FUNCTION public.product_types_search_name() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.search_name := public.catalog_search_norm(NEW.name);
  RETURN NEW;
END;
$$;
CREATE TRIGGER product_types_search_name BEFORE INSERT OR UPDATE OF name ON public.product_types
  FOR EACH ROW EXECUTE FUNCTION public.product_types_search_name();

-- 2. Przypisanie rodzaju ---------------------------------------------------------------------------------------------
CREATE FUNCTION public.product_type_match(p_name text, p_base_product_id integer, p_unit text, p_quantity numeric) RETURNS bigint
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT r.product_type_id
  FROM public.product_type_rules r
  JOIN public.product_types t ON t.id = r.product_type_id AND t.is_active
  JOIN public.base_products bp ON bp.id = p_base_product_id AND bp.name = ANY (r.base_product_names)
  WHERE p_quantity > 0
    AND (p_unit = t.unit OR (t.g_ml_equal AND p_unit IN ('g', 'ml')))
    AND public.catalog_search_norm(p_name) ~ r.include_pattern
    AND (r.exclude_pattern IS NULL OR public.catalog_search_norm(p_name) !~ r.exclude_pattern)
  ORDER BY r.priority
  LIMIT 1;
$$;

CREATE FUNCTION public.assign_product_type() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE decyzja record;
BEGIN
  SELECT product_type_id INTO decyzja FROM public.product_type_reviews WHERE product_id = NEW.id;
  IF FOUND THEN
    NEW.product_type_id := decyzja.product_type_id;
    NEW.product_type_source := 'review';
  ELSE
    NEW.product_type_id := public.product_type_match(NEW.canonical_name, NEW.base_product_id, NEW.quantity_unit, NEW.quantity_value);
    NEW.product_type_source := CASE WHEN NEW.product_type_id IS NOT NULL THEN 'rule' END;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER products_product_type BEFORE INSERT OR UPDATE OF canonical_name, base_product_id, quantity_unit, quantity_value
  ON public.products FOR EACH ROW EXECUTE FUNCTION public.assign_product_type();

-- Ponowne przypisanie wszystkich produktów (po zmianie reguł lub decyzji) i typowe opakowanie rodzajów.
-- Funkcja administracyjna (service_role / postgres). Zwraca liczbę zmienionych przypisań.
CREATE FUNCTION public.refresh_product_types() RETURNS jsonb
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE zmienione integer;
BEGIN
  WITH nowe AS (
    SELECT p.id,
      CASE WHEN rv.product_id IS NOT NULL THEN rv.product_type_id
        ELSE public.product_type_match(p.canonical_name, p.base_product_id, p.quantity_unit, p.quantity_value) END AS typ,
      CASE WHEN rv.product_id IS NOT NULL THEN 'review' END AS zrodlo
    FROM public.products p LEFT JOIN public.product_type_reviews rv ON rv.product_id = p.id
  )
  UPDATE public.products p SET product_type_id = n.typ,
    product_type_source = coalesce(n.zrodlo, CASE WHEN n.typ IS NOT NULL THEN 'rule' END)
  FROM nowe n
  WHERE n.id = p.id AND (p.product_type_id IS DISTINCT FROM n.typ
    OR p.product_type_source IS DISTINCT FROM coalesce(n.zrodlo, CASE WHEN n.typ IS NOT NULL THEN 'rule' END));
  GET DIAGNOSTICS zmienione = ROW_COUNT;
  UPDATE public.product_types t SET typical_package = x.mediana
  FROM (SELECT p.product_type_id, round(percentile_cont(0.5) WITHIN GROUP (ORDER BY p.quantity_value)::numeric, 2) AS mediana
        FROM public.products p WHERE p.product_type_id IS NOT NULL AND p.quantity_value > 0
          AND EXISTS (SELECT 1 FROM public.store_offers so WHERE so.product_id = p.id)
        GROUP BY 1) x
  WHERE x.product_type_id = t.id AND t.typical_package IS DISTINCT FROM x.mediana;
  RETURN jsonb_build_object('changed_products', zmienione,
    'typed_products', (SELECT count(*) FROM public.products WHERE product_type_id IS NOT NULL),
    'types', (SELECT count(*) FROM public.product_types WHERE is_active));
END;
$$;

-- 3. Ceny w rodzaju --------------------------------------------------------------------------------------------------
-- Cena za 1 kg / 1 l / 1 szt.
CREATE FUNCTION public.unit_price(p_price numeric, p_quantity numeric, p_unit text) RETURNS numeric
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT CASE WHEN p_price IS NOT NULL AND p_quantity > 0
    THEN round(p_price / p_quantity * CASE WHEN p_unit IN ('g', 'ml') THEN 1000 ELSE 1 END, 2) END;
$$;

-- Mediana ceny jednostkowej dziś w rodzaju (z ofert 1 opakowania); NULL, gdy mniej niż 5 ofert z ceną.
CREATE FUNCTION public.product_type_median(p_type_id bigint) RETURNS numeric
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT CASE WHEN count(*) >= 5 THEN percentile_cont(0.5) WITHIN GROUP (ORDER BY u)::numeric END
  FROM (SELECT public.unit_price(c.single_price, c.quantity_value, c.quantity_unit) AS u
        FROM public.catalog_offers c JOIN public.products p ON p.id = c.product_id
        WHERE p.product_type_id = p_type_id AND c.single_price IS NOT NULL AND c.quantity_value > 0) x;
$$;

CREATE FUNCTION public.price_suspicious(p_unit_price numeric, p_median numeric) RETURNS boolean
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT coalesce(p_unit_price < 0.4 * p_median OR p_unit_price > 3 * p_median, false);
$$;

-- Wszystkie produkty rodzaju w jednej sieci wycenione dla ilości p_needed (w jednostce rodzaju): dla każdej oferty
-- najtańszy zakup TYLKO tego produktu, który pokrywa ilość. Kolejność: niepodejrzane, cena łączna, cena jednostkowa.
CREATE FUNCTION public.product_type_store_options(p_type_id bigint, p_store_id integer, p_needed numeric) RETURNS jsonb
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE o record; t record; med numeric; n integer; n_min integer; n_max integer; ile numeric;
  pr jsonb; najl jsonb; wynik jsonb := '[]'::jsonb;
BEGIN
  SELECT * INTO t FROM public.product_types WHERE id = p_type_id;
  IF NOT FOUND THEN RETURN '[]'::jsonb; END IF;
  med := public.product_type_median(p_type_id);
  FOR o IN SELECT c.*, to_jsonb(c) AS dane FROM public.catalog_offers c JOIN public.products p ON p.id = c.product_id
    WHERE p.product_type_id = p_type_id AND c.store_id = p_store_id AND c.quantity_value > 0
      AND c.sale_mode IN ('package', 'bulk') ORDER BY c.offer_id
  LOOP
    najl := NULL;
    IF o.sale_mode = 'bulk' THEN
      pr := public.purchase_price(o.dane, p_needed / o.quantity_value);
      IF pr->>'cost' IS NOT NULL THEN
        najl := pr || jsonb_build_object('package_count', NULL, 'quantity', p_needed);
      END IF;
    ELSE
      n_min := ceil(p_needed / o.quantity_value)::integer;
      CONTINUE WHEN n_min > 1000;
      n_max := n_min;
      -- promocja „przy zakupie N” / zestaw: sprawdź też zakup do progu promocji, jeśli wyjdzie taniej
      IF o.verified_promotion THEN
        n_max := greatest(n_max, coalesce((o.promo_rule->>'min_quantity')::integer, 1));
        IF o.promo_rule->>'kind' = 'bundle' THEN
          n_max := ceil(n_max::numeric / (o.promo_rule->>'bundle_size')::integer)::integer * (o.promo_rule->>'bundle_size')::integer;
        END IF;
        n_max := least(n_max, 1000);
      END IF;
      FOR n IN n_min..n_max LOOP
        pr := public.purchase_price(o.dane, n);
        CONTINUE WHEN pr->>'cost' IS NULL;
        IF najl IS NULL OR (pr->>'cost')::numeric < (najl->>'cost')::numeric THEN
          najl := pr || jsonb_build_object('package_count', n, 'quantity', n * o.quantity_value);
        END IF;
      END LOOP;
    END IF;
    CONTINUE WHEN najl IS NULL;
    ile := (najl->>'quantity')::numeric;
    wynik := wynik || jsonb_build_array(jsonb_build_object(
      'offer_id', o.offer_id, 'product_id', o.product_id, 'name', o.product_name,
      'package', jsonb_build_object('quantity', o.quantity_value, 'unit', o.quantity_unit, 'label', o.gramatura_norm),
      'package_count', najl->'package_count', 'quantity', ile, 'unit', t.unit, 'sale_mode', o.sale_mode,
      'total_price', (najl->>'cost')::numeric, 'regular_total', (najl->>'regular_total')::numeric,
      'unit_price', public.unit_price((najl->>'cost')::numeric, ile, t.unit),
      'unit_price_per', public.catalog_unit_label(t.unit),
      'promotion_applied', (najl->>'promotion_applied')::boolean,
      'requires_card', (najl->>'requires_card')::boolean, 'requires_activation', (najl->>'requires_activation')::boolean,
      'condition', o.promo_condition, 'valid_from', o.valid_from, 'valid_to', o.valid_to,
      'price_source', o.price_source, 'observed_at', o.regular_price_observed_at, 'image_url', o.image_url,
      'suspicious', public.price_suspicious(public.unit_price(o.single_price, o.quantity_value, o.quantity_unit), med)));
  END LOOP;
  RETURN coalesce((SELECT jsonb_agg(x ORDER BY (x->>'suspicious')::boolean, (x->>'total_price')::numeric,
      (x->>'unit_price')::numeric, (x->>'product_id')::bigint) FROM jsonb_array_elements(wynik) x), '[]'::jsonb);
END;
$$;

-- Ilość pozycji w jednostce rodzaju: „N szt” rodzaju liczonego na wagę = N × typowe opakowanie.
CREATE FUNCTION public.product_type_needed(p_type_id bigint, p_quantity numeric, p_unit text) RETURNS numeric
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE t record;
BEGIN
  SELECT * INTO t FROM public.product_types WHERE id = p_type_id AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'Nie ma takiego rodzaju produktu.' USING ERRCODE = '22023'; END IF;
  IF p_quantity IS NULL OR p_quantity <= 0 OR p_quantity > 100000 OR scale(p_quantity) > 2 THEN
    RAISE EXCEPTION 'Podaj poprawną ilość (maksymalnie 100000, do dwóch miejsc po przecinku).' USING ERRCODE = '22023'; END IF;
  IF p_unit = 'szt' AND p_quantity <> trunc(p_quantity) THEN
    RAISE EXCEPTION 'Podaj całkowitą liczbę sztuk.' USING ERRCODE = '22023'; END IF;
  IF p_unit = t.unit OR (t.g_ml_equal AND p_unit IN ('g', 'ml')) THEN RETURN p_quantity; END IF;
  IF p_unit = 'szt' AND t.unit IN ('g', 'ml') THEN
    RETURN p_quantity * coalesce(t.typical_package, CASE WHEN t.unit IN ('g', 'ml') THEN 1000 ELSE 1 END);
  END IF;
  RAISE EXCEPTION 'Jednostka nie pasuje do rodzaju produktu.' USING ERRCODE = '22023';
END;
$$;

-- 4. API katalogu ----------------------------------------------------------------------------------------------------
-- Element listy: rodzaj produktu (kind: "type").
CREATE FUNCTION public.catalog_type_item(p_type_id bigint) RETURNS jsonb
LANGUAGE sql STABLE SET search_path = '' AS $$
  WITH t AS (SELECT * FROM public.product_types WHERE id = p_type_id),
  m AS MATERIALIZED (SELECT public.product_type_median(p_type_id) AS med),   -- raz, nie dla każdej oferty
  o AS (
    SELECT c.*, public.unit_price(c.single_price, c.quantity_value, c.quantity_unit) AS unit_price
    FROM public.catalog_offers c JOIN public.products p ON p.id = c.product_id
    WHERE p.product_type_id = p_type_id
  ), best AS (
    SELECT o.* FROM o, m WHERE o.unit_price IS NOT NULL AND NOT public.price_suspicious(o.unit_price, m.med)
    ORDER BY o.unit_price, o.single_price, o.offer_id LIMIT 1
  )
  SELECT jsonb_build_object(
    'kind', 'type', 'type_id', t.id, 'group_id', NULL, 'product_id', NULL, 'name', t.name, 'unit', t.unit,
    'g_ml_equal', t.g_ml_equal,
    'default_quantity', coalesce(t.default_quantity, t.typical_package, CASE WHEN t.unit IN ('g', 'ml') THEN 1000 ELSE 1 END),
    'typical_package', t.typical_package,
    'product_count', (SELECT count(DISTINCT product_id) FROM o),
    'offer_count', (SELECT count(*) FROM o),
    'store_count', (SELECT count(DISTINCT store_id) FROM o),
    'stores_with_price_today', (SELECT count(DISTINCT store_id) FROM o WHERE single_price IS NOT NULL),
    'price_from', (SELECT jsonb_build_object('unit_price', b.unit_price, 'unit_price_per', public.catalog_unit_label(t.unit),
        'package_price', b.single_price, 'package_quantity', b.quantity_value, 'package_unit', b.quantity_unit,
        'store', jsonb_build_object('id', b.store_id, 'slug', b.store_slug, 'name', b.store_name), 'offer_id', b.offer_id) FROM best b),
    'image_url', (SELECT image_url FROM o WHERE image_url IS NOT NULL ORDER BY unit_price NULLS LAST, offer_id LIMIT 1))
  FROM t;
$$;

-- Ekran rodzaju: produkty ze wszystkich sieci (albo jednej), od najtańszego za kg / l / szt dziś.
CREATE FUNCTION public.catalog_type(p_type_id bigint, p_store_id integer DEFAULT NULL, p_limit integer DEFAULT 30, p_offset integer DEFAULT 0)
RETURNS jsonb
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE item jsonb; sciezka jsonb; med numeric; total bigint; produkty jsonb;
  lim integer := greatest(1, least(coalesce(p_limit, 30), 100)); off integer := greatest(coalesce(p_offset, 0), 0);
BEGIN
  PERFORM public.catalog_require_reader();
  IF NOT EXISTS (SELECT 1 FROM public.product_types WHERE id = p_type_id AND is_active) THEN
    RAISE EXCEPTION 'Nie ma takiego rodzaju produktu.' USING ERRCODE = 'PT404'; END IF;
  item := public.catalog_type_item(p_type_id);
  med := public.product_type_median(p_type_id);
  SELECT jsonb_build_object('category', jsonb_build_object('slug', c.slug, 'name', c.name),
    'subcategory', jsonb_build_object('slug', s.slug, 'name', s.name, 'verification_status', s.verification_status))
  INTO sciezka FROM public.product_types t JOIN public.catalog_subcategories s ON s.id = t.subcategory_id
  JOIN public.categories c ON c.id = s.category_id WHERE t.id = p_type_id;
  WITH oferty AS (
    SELECT c.offer_id, c.product_id, c.store_id, public.unit_price(c.single_price, c.quantity_value, c.quantity_unit) AS u
    FROM public.catalog_offers c JOIN public.products p ON p.id = c.product_id
    WHERE p.product_type_id = p_type_id AND (p_store_id IS NULL OR c.store_id = p_store_id)
  ), prod AS (
    SELECT product_id, min(u) FILTER (WHERE NOT public.price_suspicious(u, med)) AS najl,
      min(u) AS najl_wszystkie FROM oferty GROUP BY product_id
  ), strona AS (
    SELECT p.*, pr.najl, pr.najl_wszystkie FROM prod pr JOIN public.products p ON p.id = pr.product_id
    ORDER BY pr.najl NULLS LAST, pr.najl_wszystkie NULLS LAST, p.canonical_name, p.id LIMIT lim OFFSET off
  )
  SELECT (SELECT count(*) FROM prod),
    (SELECT coalesce(jsonb_agg(jsonb_build_object(
      'product_id', s.id, 'name', s.canonical_name, 'ean', s.ean,
      'package', jsonb_build_object('quantity', s.quantity_value, 'unit', s.quantity_unit, 'label', s.gramatura_norm),
      'sale_mode', s.sale_mode, 'image_url', s.image_url,
      'offers', (SELECT coalesce(jsonb_agg(public.catalog_offer(o.offer_id)
            || jsonb_build_object('suspicious', public.price_suspicious(o.u, med)) ORDER BY o.u NULLS LAST, o.store_id), '[]'::jsonb)
         FROM oferty o WHERE o.product_id = s.id))
      ORDER BY s.najl NULLS LAST, s.najl_wszystkie NULLS LAST, s.canonical_name, s.id), '[]'::jsonb) FROM strona s)
  INTO total, produkty;
  RETURN jsonb_build_object('version', 1, 'type', item || jsonb_build_object('path', sciezka, 'median_unit_price', round(med, 2)),
    'store_id', p_store_id, 'total', total, 'limit', lim, 'offset', off, 'products', produkty);
END;
$$;

-- Wyszukiwanie i gałąź z rodzajami. Bez p_with_types (domyślnie false) wynik jak dotąd.
-- Z p_with_types: najpierw rodzaje, potem grupy i pojedyncze produkty, które NIE są w całości w rodzajach.
DROP FUNCTION public.catalog_search(text, integer, integer);
CREATE FUNCTION public.catalog_search(p_query text, p_limit integer DEFAULT 30, p_offset integer DEFAULT 0, p_with_types boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE q text := public.catalog_search_norm(left(coalesce(p_query, ''), 200)); toks text[];
  lim integer := greatest(1, least(coalesce(p_limit, 30), 100)); off integer := greatest(coalesce(p_offset, 0), 0);
  total bigint; items jsonb;
BEGIN
  PERFORM public.catalog_require_reader();
  toks := array_remove(string_to_array(q, ' '), '');
  IF coalesce(array_length(toks, 1), 0) = 0 THEN
    RETURN jsonb_build_object('version', 1, 'query', q, 'total', 0, 'limit', lim, 'offset', off, 'items', '[]'::jsonb);
  END IF;
  WITH kandydaci AS (
    SELECT g.id, g.name, g.group_key, coalesce(g.search_name, '') AS gn, count(*) AS n,
      bool_or(public.catalog_search_match(coalesce(g.search_name, '') || ' ' || coalesce(p.search_text, '')
        || CASE WHEN g.group_key LIKE 'product:%' THEN ' ' || coalesce(bp.search_name, '') ELSE '' END, toks)) AS w_produkcie,
      bool_and(p.product_type_id IS NOT NULL) AS w_rodzajach
    FROM public.comparison_groups g
    JOIN public.products p ON p.comparison_group_id = g.id
    JOIN public.base_products bp ON bp.id = p.base_product_id AND bp.subcategory_id IS NOT NULL
    WHERE EXISTS (SELECT 1 FROM public.store_offers so JOIN public.stores st ON st.id = so.store_id AND st.is_active WHERE so.product_id = p.id)
    GROUP BY g.id
  ), rodzaje AS (
    SELECT t.id, t.name, coalesce(t.search_name, '') AS tn, count(*) AS n,
      bool_or(public.catalog_search_match(coalesce(t.search_name, '') || ' ' || coalesce(p.search_text, ''), toks)) AS w_produkcie
    FROM public.product_types t JOIN public.products p ON p.product_type_id = t.id
    WHERE p_with_types AND t.is_active
      AND EXISTS (SELECT 1 FROM public.store_offers so JOIN public.stores st ON st.id = so.store_id AND st.is_active WHERE so.product_id = p.id)
    GROUP BY t.id
  ), trafienia AS (
    SELECT 'group'::text AS rodzaj, k.id, k.name, k.n, (CASE WHEN k.gn = q THEN 200 WHEN k.gn LIKE q || '%' THEN 150
        WHEN public.catalog_search_match(k.gn, toks) THEN 120 ELSE 60 END
      + CASE WHEN k.group_key LIKE 'product:%' THEN 0 ELSE 40 END) AS score
    FROM kandydaci k
    WHERE k.w_produkcie AND NOT (p_with_types AND k.w_rodzajach)
    UNION ALL
    SELECT 'type', r.id, r.name, r.n, (CASE WHEN r.tn = q THEN 200 WHEN r.tn LIKE q || '%' THEN 150
        WHEN public.catalog_search_match(r.tn, toks) THEN 120 ELSE 60 END) + 1000
    FROM rodzaje r WHERE r.w_produkcie
  )
  SELECT (SELECT count(*) FROM trafienia),
    (SELECT coalesce(jsonb_agg(CASE WHEN x.rodzaj = 'type' THEN public.catalog_type_item(x.id) ELSE public.catalog_item(x.id) END
       ORDER BY x.score DESC, x.n DESC, x.name, x.id), '[]'::jsonb)
     FROM (SELECT * FROM trafienia ORDER BY score DESC, n DESC, name, id LIMIT lim OFFSET off) x)
  INTO total, items;
  RETURN jsonb_build_object('version', 1, 'query', q, 'total', total, 'limit', lim, 'offset', off, 'items', items);
END;
$$;

DROP FUNCTION public.catalog_branch(text, integer, integer);
CREATE FUNCTION public.catalog_branch(p_subcategory text, p_limit integer DEFAULT 30, p_offset integer DEFAULT 0, p_with_types boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE sc record; lim integer := greatest(1, least(coalesce(p_limit, 30), 100)); off integer := greatest(coalesce(p_offset, 0), 0);
  total bigint; items jsonb;
BEGIN
  PERFORM public.catalog_require_reader();
  SELECT s.id, s.slug, s.name, s.verification_status, c.slug AS category_slug, c.name AS category_name INTO sc
  FROM public.catalog_subcategories s JOIN public.categories c ON c.id = s.category_id WHERE s.slug = p_subcategory;
  IF NOT FOUND THEN RAISE EXCEPTION 'Nie ma takiej podkategorii.' USING ERRCODE = 'PT404'; END IF;
  WITH grupy AS (
    SELECT g.id, g.name, g.group_key FROM public.comparison_groups g
    WHERE EXISTS (SELECT 1 FROM public.products p JOIN public.base_products bp ON bp.id = p.base_product_id
      JOIN public.store_offers so ON so.product_id = p.id JOIN public.stores st ON st.id = so.store_id AND st.is_active
      WHERE p.comparison_group_id = g.id AND bp.subcategory_id = sc.id AND NOT (p_with_types AND p.product_type_id IS NOT NULL))
  ), rodzaje AS (
    SELECT t.id, t.name, t.display_order FROM public.product_types t
    WHERE p_with_types AND t.is_active AND t.subcategory_id = sc.id
      AND EXISTS (SELECT 1 FROM public.products p JOIN public.store_offers so ON so.product_id = p.id
        JOIN public.stores st ON st.id = so.store_id AND st.is_active WHERE p.product_type_id = t.id)
  ), elementy AS (
    SELECT 0 AS kolejnosc, 'type'::text AS rodzaj, id, name, display_order AS poz FROM rodzaje
    UNION ALL
    SELECT CASE WHEN group_key LIKE 'product:%' THEN 2 ELSE 1 END, 'group', id, name, 0 FROM grupy
  )
  SELECT (SELECT count(*) FROM elementy),
    (SELECT coalesce(jsonb_agg(CASE WHEN x.rodzaj = 'type' THEN public.catalog_type_item(x.id) ELSE public.catalog_item(x.id) END
       ORDER BY x.kolejnosc, x.poz, x.name, x.id), '[]'::jsonb)
     FROM (SELECT * FROM elementy ORDER BY kolejnosc, poz, name, id LIMIT lim OFFSET off) x)
  INTO total, items;
  RETURN jsonb_build_object('version', 1,
    'subcategory', jsonb_build_object('id', sc.id, 'slug', sc.slug, 'name', sc.name, 'verification_status', sc.verification_status,
      'category', jsonb_build_object('slug', sc.category_slug, 'name', sc.category_name)),
    'total', total, 'limit', lim, 'offset', off, 'items', items);
END;
$$;

