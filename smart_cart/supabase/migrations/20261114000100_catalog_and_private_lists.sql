CREATE OR REPLACE FUNCTION public.touch_list_from_item() RETURNS trigger
LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
  UPDATE public.shopping_lists SET updated_at=now() WHERE id=CASE WHEN TG_OP='DELETE' THEN OLD.list_id ELSE NEW.list_id END;
  RETURN NULL;
END;
$$;
CREATE TRIGGER touch_list AFTER INSERT OR UPDATE OR DELETE ON public.shopping_list_items
  FOR EACH ROW EXECUTE FUNCTION public.touch_list_from_item();
REVOKE ALL ON FUNCTION public.classify_comparison_product(),public.validate_list_item(),public.touch_list_from_item() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.classify_comparison_product(),public.validate_list_item(),public.touch_list_from_item() TO service_role;
