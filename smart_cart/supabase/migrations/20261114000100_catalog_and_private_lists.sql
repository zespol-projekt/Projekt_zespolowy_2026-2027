CREATE TABLE public.shopping_lists (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX shopping_lists_owner ON public.shopping_lists(owner_id,updated_at DESC);
CREATE TABLE public.shopping_list_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  list_id uuid NOT NULL REFERENCES public.shopping_lists(id) ON DELETE CASCADE,
  group_id bigint NOT NULL REFERENCES public.comparison_groups(id) ON DELETE RESTRICT,
  selected_product_id bigint REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity numeric(12,2) NOT NULL CHECK (quantity>0 AND quantity<=100000),
  unit text NOT NULL CHECK (unit IN ('g','ml','szt')),
  extra_store_ids integer[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(list_id,group_id)
);
CREATE INDEX shopping_list_items_list ON public.shopping_list_items(list_id,created_at);
CREATE TABLE public.favorite_groups (
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  group_id bigint NOT NULL REFERENCES public.comparison_groups(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(owner_id,group_id)
);
CREATE TRIGGER shopping_lists_updated BEFORE UPDATE ON public.shopping_lists
  FOR EACH ROW EXECUTE FUNCTION public.fn_set_updated_at();
