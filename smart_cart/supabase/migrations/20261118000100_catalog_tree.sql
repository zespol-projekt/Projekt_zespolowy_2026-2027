-- 2. Podkategorie (poziom między kategorią a grupą porównania).
CREATE TABLE public.catalog_subcategories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 80),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  display_order smallint NOT NULL CHECK (display_order > 0),
  verification_status text NOT NULL DEFAULT 'preliminary' CHECK (verification_status IN ('preliminary', 'in_progress', 'reviewed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (category_id, name),
  UNIQUE (id, category_id)
);
